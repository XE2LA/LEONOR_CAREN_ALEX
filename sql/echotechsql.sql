-- ---------------------------
-- 1. PROYECTOS (Debe crearse antes porque empleados depende de ella)
-- ---------------------------
CREATE TABLE proyectos (
    id_proyecto       NUMBER(5)           PRIMARY KEY,
    nombre_proyecto   VARCHAR2(60)        NOT NULL,
    descripcion       VARCHAR2(400),
    fecha_inicio      DATE                NOT NULL
);

-- ---------------------------
-- 2. USUARIOS Y SESIÓN (LEONOR)
-- ---------------------------
CREATE TABLE usuarios (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut VARCHAR2(12) UNIQUE NOT NULL,
    nombre VARCHAR2(50) NOT NULL,
    correo VARCHAR2(100) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    privilegio VARCHAR2(20) NOT NULL,
    
    CONSTRAINT chk_privilegio_valido CHECK (privilegio IN ('admin', 'empleado'))
);

CREATE TABLE sesion (
    id_sesion NUMBER PRIMARY KEY,
    id_usuario NUMBER NOT NULL,
    token VARCHAR2(255) NOT NULL,
    vencimiento TIMESTAMP NOT NULL,
    
    CONSTRAINT fk_sesion_usuario FOREIGN KEY (id_usuario) 
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

-- ---------------------------
-- 3. DEPARTAMENTOS Y EMPLEADOS (CAREN)
-- ---------------------------
CREATE TABLE departamentos (
    id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_depa VARCHAR2(100) NOT NULL,
    gerente VARCHAR2(100) NOT NULL
);

CREATE TABLE empleados (
    id_usuario NUMBER PRIMARY KEY,
    id_departamento NUMBER,
    direccion VARCHAR2(150),
    num_telefonico VARCHAR2(20),
    fecha_contrato DATE,
    salario NUMBER(10, 2),
    id_proyecto NUMBER(5), -- Corregido de 'proyecto' a 'id_proyecto'
    
    CONSTRAINT fk_emp_usuario FOREIGN KEY (id_usuario) 
        REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
        
    CONSTRAINT fk_emp_depto FOREIGN KEY (id_departamento) 
        REFERENCES departamentos(id_departamento),
        
    CONSTRAINT fk_emp_proyecto FOREIGN KEY (id_proyecto) 
        REFERENCES proyectos(id_proyecto)
);

CREATE TABLE admins (
    id_usuario NUMBER PRIMARY KEY,
    dept_cargo VARCHAR2(100),
    CONSTRAINT fk_admin_empleado FOREIGN KEY (id_usuario) 
        REFERENCES empleados(id_usuario) ON DELETE CASCADE
);

-- ---------------------------
-- 4. REGISTRO TIEMPO E INFORMES (ALEX)
-- ---------------------------
CREATE TABLE registro_tiempo (
    id_registro         NUMBER(5)           PRIMARY KEY,
    fecha               DATE                NOT NULL,
    cantidad_horas      NUMBER(3)           NOT NULL,
    descripcion_tarea   VARCHAR2(500),
    id_empleado         NUMBER              NOT NULL,
    id_proyecto         NUMBER              NOT NULL,
    
    CONSTRAINT fk_empleado_tiempo FOREIGN KEY (id_empleado) REFERENCES empleados(id_usuario),
    CONSTRAINT fk_proyecto_tiempo FOREIGN KEY (id_proyecto) REFERENCES proyectos(id_proyecto)
);

CREATE TABLE informe (
    id_informe          NUMBER(9)           PRIMARY KEY,
    fecha_generacion    DATE                DEFAULT SYSDATE,
    id_empleado         NUMBER,
    
    CONSTRAINT fk_informe_empleado FOREIGN KEY (id_empleado) REFERENCES empleados(id_usuario)
);